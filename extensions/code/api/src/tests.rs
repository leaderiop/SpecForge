#[test]
fn a_recorded_break_reads_changed_narrowed_removed_and_added() {
    let fresh = read_js_model(CHANGED_MODEL).expect("the model reads");
    let accepted = read_js_report(TAGGED_REPORT).expect("the report reads");
    let facts = api_facts_against(&fresh, &accepted, &[]);
    let at = |path: &str| -> Judged {
        judged(&facts)
            .into_iter()
            .find(|j| j.0 == path)
            .unwrap_or_else(|| panic!("{path}"))
    };
    let some = |text: &str| Some(text.to_string());
    let create = at("create");
    assert_eq!(
        (create.1.as_str(), create.2),
        (
            "changed",
            some("export function create(o: Options): Widget;")
        )
    );
    // The class went `@beta`, and its members with no tag of their own with it.
    for member in ["Widget", "Widget.render", "Widget.size"] {
        assert_eq!(
            (at(member).1.as_str(), at(member).3),
            ("narrowed", some("Public"))
        );
    }
    let trial = at("trial");
    assert_eq!(
        (trial.1.as_str(), trial.2, trial.3),
        (
            "removed",
            some("export function trial(): void;"),
            some("Alpha")
        )
    );
    assert_eq!(at("added").1, "added");
    let changes: Vec<String> = judged(&facts).into_iter().map(|j| j.1).collect();
    assert_eq!(changes.iter().filter(|c| *c == "removed").count(), 1);
    assert!(facts.iter().all(|f| !f.id.contains("_hidden")));
    insta::assert_json_snapshot!("widget_changed_against_tagged", facts);
}

#[test]
fn a_tag_line_with_more_modifiers_reads_its_release_tag() {
    let text = report(
        "// Warning: (ae-internal-missing-underscore) The name \"Old\" should be prefixed\n//\n\
         // @internal @deprecated (undocumented)\nexport class Old {\n    // (undocumented)\n    \
         static get kind(): string;\n    [Symbol.iterator](): Iterator<string>;\n    new (x: number): Old;\n    \
         (y: string): void;\n}\n\nexport function untagged(): void;",
    );
    let entries = read_js_report(&text).expect("the report reads");
    let read: Vec<(String, &str, Option<&str>)> = entries
        .iter()
        .map(|e| (e.path.join("."), e.kind.as_str(), e.tag.as_deref()))
        .collect();
    let expected = [
        ("Old", "class", "Internal"),
        ("Old.kind", "field", "Internal"),
        ("Old.[Symbol.iterator]", "method", "Internal"),
        ("Old.new()", "other", "Internal"),
        ("Old.()", "other", "Internal"),
        ("untagged", "function", "Public"),
    ];
    let expected: Vec<(String, &str, Option<&str>)> = expected
        .iter()
        .map(|(path, kind, tag)| (path.to_string(), *kind, Some(*tag)))
        .collect();
    assert_eq!(read, expected);
}

#[test]
fn a_malformed_report_is_an_error_naming_why() {
    let ok = report("export function f(): void;");
    assert_eq!(read_js_report(&ok).expect("reads").len(), 1);
    let cases = [
        (
            ok.replacen("## API Report File for \"p\"", "## Something else", 1),
            "title",
        ),
        (ok.replacen("```ts", "```js", 1), "fence"),
        (
            ok.trim_end().trim_end_matches('`').to_string(),
            "never closed",
        ),
        (
            report("<<<<<<< HEAD\nexport function f(): void;"),
            "merge-conflict",
        ),
        (
            report("export function f(): void;\n======="),
            "merge-conflict",
        ),
        (report(">>>>>>> theirs"), "merge-conflict"),
        (report("export class W {\n    m(): void;"), "never closed"),
        (report("export type T = {\n    a: string;"), "never ended"),
        (report("}"), "closing brace"),
        (report("export { X } from './x';"), "line 7"),
        (report(&"export namespace n {\n".repeat(65)), "deeper"),
    ];
    for (text, why) in cases {
        let error = read_js_report(&text).expect_err(&text);
        assert!(error.contains(why), "{text}: {error}");
    }
    assert!(
        read_js_report(&report("export function f(): void;\n======="))
            .unwrap_err()
            .contains("line 8")
    );
}

#[test]
fn a_refused_file_still_names_the_package_or_crate_it_was_meant_for() {
    let conflicted = report("<<<<<<< HEAD\nexport function f(): void;");
    assert!(read_js_report(&conflicted).is_err());
    assert_eq!(js_report_package(&conflicted), Some("p"));
    assert_eq!(js_report_package("# Notes\n\nprose\n"), None);
    assert_eq!(js_report_package("## API Report File for \"\"\n"), None);

    assert_eq!(
        rust_text_crate("<<<<<<< HEAD\npub mod demo\ngarbage\n"),
        Some("demo")
    );
    assert_eq!(rust_text_crate(RUST), Some("example_api"));
    assert_eq!(rust_text_crate("pub mod demo::inner\nprose\n"), None);
    assert_eq!(rust_text_crate("prose\n"), None);
}
