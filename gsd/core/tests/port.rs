/// Checks one asset against its upstream file: the header, then every line.
fn check_body(file: &str) -> usize {
    let (_, body) = upstream(file);
    check_lines(
        file,
        &format!("agents/{file}"),
        &read(&assets_dir().join(file)),
        &body,
        &ported(),
        &|n| REWRITTEN.contains(&(file, n)),
    )
}

