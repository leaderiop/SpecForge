//! The marker (ADR 0292): the line that makes a file install's. It names the host, the extension and version it was
//! rendered from, what kind of contribution and its id, and the SHA-256 of the file without that line, so a hand edit is
//! seen from the file alone. A file without a marker is never written, moved or removed.

use specforge_package::Sha256;

use super::Host;
use super::port::Source;

/// What a marker line starts with.
pub const PREFIX: &str = "# generated by specforge install (";

/// The line an adapter puts where the marker goes in its template; [`stamp`] replaces it.
pub const PLACEHOLDER: &str = "@@specforge-marker@@";

/// How far into a file a marker may stand: after a frontmatter fence, never deeper.
const SEARCHED: usize = 4;

/// `template` with its [`PLACEHOLDER`] line replaced by the marker line for `source` on `host`.
pub fn stamp(host: Host, source: &Source, template: &str) -> String {
    let without = remove_line(template, PLACEHOLDER);
    let digest = Sha256::of(without.as_bytes());
    let line = format!(
        "{PREFIX}{}) from {}@{} {} {}; edits are overwritten; sha256:{digest}",
        host.as_str(),
        source.extension,
        source.version,
        source.kind,
        source.id,
    );
    template.replacen(PLACEHOLDER, &line, 1)
}

/// `text` without its first line that is (or starts with) `needle`, and that line's newline.
fn remove_line(text: &str, needle: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut removed = false;
    for line in text.split_inclusive('\n') {
        if !removed && line.trim_end_matches('\n').starts_with(needle) {
            removed = true;
            continue;
        }
        out.push_str(line);
    }
    out
}

/// What a file says about whose it is.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Mark {
    /// No marker: the file is not install's.
    Foreign,
    /// Install's, for `host`; `intact`: it still holds what the marker's digest names.
    Ours { host: String, intact: bool },
}

/// Read the marker of `text`.
pub fn inspect(text: &str) -> Mark {
    let Some(line) = text.lines().take(SEARCHED).find(|l| l.starts_with(PREFIX)) else {
        return Mark::Foreign;
    };
    let Some(host) = line[PREFIX.len()..].split_once(')').map(|(h, _)| h) else {
        return Mark::Foreign;
    };
    let claimed = line.rsplit_once("sha256:").map(|(_, hex)| hex.trim());
    let digest = Sha256::of(remove_line(text, PREFIX).as_bytes()).to_string();
    Mark::Ours {
        host: host.to_string(),
        intact: claimed == Some(digest.as_str()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source() -> Source {
        Source {
            extension: "@t/core".into(),
            version: "0.4.0".into(),
            kind: "agent",
            id: "t-planner".into(),
        }
    }

    #[test]
    fn a_marker_digest_ignores_its_own_line() {
        let template = format!("---\n{PLACEHOLDER}\nname: a\n---\nbody\n");
        let stamped = stamp(Host::ClaudeCode, &source(), &template);
        assert!(
            stamped.contains("from @t/core@0.4.0 agent t-planner; edits are overwritten; sha256:")
        );
        assert_eq!(
            inspect(&stamped),
            Mark::Ours {
                host: "claude-code".into(),
                intact: true
            }
        );
        // The same body stamped for another source has another line and the same digest.
        let other = Source {
            id: "other".into(),
            ..source()
        };
        let restamped = stamp(Host::ClaudeCode, &other, &template);
        assert_ne!(stamped, restamped);
        assert_eq!(
            stamped.rsplit_once("sha256:").unwrap().1.lines().next(),
            restamped.rsplit_once("sha256:").unwrap().1.lines().next()
        );
    }

    #[test]
    fn an_edit_is_seen_and_a_file_without_a_marker_is_foreign() {
        let stamped = stamp(
            Host::Codex,
            &source(),
            &format!("{PLACEHOLDER}\nname = 'a'\n"),
        );
        let edited = stamped.replace("name = 'a'", "name = 'b'");
        assert_eq!(
            inspect(&edited),
            Mark::Ours {
                host: "codex".into(),
                intact: false
            }
        );
        assert_eq!(inspect("---\nname: mine\n---\n"), Mark::Foreign);
        assert_eq!(inspect(""), Mark::Foreign);
        // A marker buried below the searched lines is no marker.
        let deep = format!("a\nb\nc\nd\n{stamped}");
        assert_eq!(inspect(&deep), Mark::Foreign);
    }
}
