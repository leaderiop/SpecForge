//! `doctor` and the hosts (ADR 0292): a host file edited since install, and an install stale against the project.

use serde_json::json;
use specforge_project::testing::GsdHosts;
use specforge_test_macros::test as specforge_test;

use crate::host_support::{host_findings, hosted, hosts_project};

#[specforge_test(
    behavior = "install_into_a_host",
    verify = "doctor reports a host file edited since install and an install stale against the project, and nothing for a directory without a marker"
)]
fn doctor_reports_an_edited_and_a_stale_install() {
    let project = hosts_project(json!({}), json!({}));
    // A hand-written host directory holds no marker: nothing to report.
    project.write(
        ".claude/agents/mine.md",
        "---\nname: mine\n---\nhand written\n",
    );
    let hosted = hosted(project, GsdHosts::new());
    assert!(host_findings(&hosted).is_empty());

    // A file install wrote, edited by hand.
    hosted.project.write(
        ".claude/skills/t-ns-context/SKILL.md",
        "---\n# generated by specforge install (claude-code) from @t/core@0.4.0 skill t-ns-context; edits are overwritten; sha256:00\nname: t-ns-context\n---\nedited\n",
    );
    let found = host_findings(&hosted);
    assert!(
        found
            .iter()
            .any(|f| f.starts_with("host_file_edited .claude/skills/t-ns-context/SKILL.md")),
        "{found:?}"
    );
    // An agent the project would now render differently (or not at all) is stale.
    assert!(
        found.iter().any(|f| f.starts_with("host_install_stale")),
        "{found:?}"
    );
}
