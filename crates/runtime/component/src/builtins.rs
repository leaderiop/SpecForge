/// (name, bytes) of every builtin, read from [`BUILTINS`]: what the extension load reads
/// (`specforge_installed::Builtins`).
pub const BUILTIN_EXTENSIONS: &[(&str, &[u8])] = &{
    let mut out: [(&str, &[u8]); BUILTINS.len()] = [("", &[]); BUILTINS.len()];
    let mut i = 0;
    while i < BUILTINS.len() {
        out[i] = (BUILTINS[i].name, BUILTINS[i].bytes);
        i += 1;
    }
    out
};

/// The builtins' candidate vocabulary: each kind keyword they declare with the list of builtins that
/// declare it (a keyword may have several declarers, ADR 0369), and each enhancement field with its
/// one declaring builtin (a field keeps one, ADR 0369 D4), as
/// `specforge_registry::CandidateVocabulary::to_json` writes it. Generated by
/// `cargo run -p xtask --bin revendor` from the pinned declarations (ADR 0122), never edited; the
/// session hands it to the registry build for the checks' suggestions.
pub const BUILTIN_VOCABULARY: &str = include_str!("../data/builtin-vocabulary.json");

/// Test support: puts the builtin Wasm extensions `requested`
/// (`specforge.json` entries, read by [`ExtensionEntry`]: a legacy
/// `name@version` names the builtin too) names into a runtime outside the
/// extension load (`Installed::load`).
///
/// Other entries (installed extensions, `.wasm` files) are skipped.
#[cfg(feature = "testing")]
pub fn load_builtins_for(runtime: &dyn WasmRuntime, requested: &[String]) -> Result<(), LoadError> {
    for (name, wasm_bytes) in BUILTIN_EXTENSIONS {
        if requested
            .iter()
            .any(|entry| ExtensionEntry::parse(entry) == ExtensionEntry::Named(name))
        {
            runtime.load(name, wasm_bytes, Provenance::builtin(wasm_bytes))?;
        }
    }
    Ok(())
}

/// Test support: puts every embedded builtin component into a runtime outside the extension load
/// (`Installed::load`). It is for a test that calls components, never for one that builds a registry
/// from what it loads: two builtins that declare one kind keyword are E026 in a registry build, so a
/// registry is built from one [`Family`] and loaded with [`load_family`] (ADR 0369 D3).
#[cfg(feature = "testing")]
pub fn load_builtins(runtime: &dyn WasmRuntime) -> Result<(), LoadError> {
    for (name, wasm_bytes) in BUILTIN_EXTENSIONS {
        runtime.load(name, wasm_bytes, Provenance::builtin(wasm_bytes))?;
    }
    Ok(())
}

/// One of the two sets of builtins that load into one registry (ADR 0369 D3). Two builtins that declare
/// one kind keyword are E026 in a registry build, so a test that builds a registry from builtins
/// builds it from one set.
#[cfg(feature = "testing")]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Family {
    /// The twenty-six builtins of the `@specforge/*` starter set and what they load with.
    Old,
    /// `@gsd/core` with its peers and the collectors that need `@code/core`.
    Gsd,
}

#[cfg(feature = "testing")]
impl Family {
    /// Both sets.
    pub const ALL: [Family; 2] = [Family::Old, Family::Gsd];

    /// The names of the set, as ADR 0369 D3 lists them. The old set is in [`BUILTINS`] order; the gsd
    /// set names `@gsd/core` and `@gsd/import` first, then the nineteen builtins it shares with the old set
    /// (`@specforge/vitest` stays in the old set only).
    pub const fn names(self) -> &'static [&'static str] {
        match self {
            Family::Old => &[
                "@specforge/product",
                "@specforge/software",
                "@specforge/governance",
                "@specforge/formal",
                "@specforge/testing",
                "@specforge/cargo-test",
                "@specforge/vitest",
                "@code/core",
                "@javascript/node-test",
                "@specforge/checks",
                "@rust/cargo",
                "@rust/source",
                "@rust/test",
                "@javascript/source",
                "@rust/coverage",
                "@rust/lint",
                "@rust/deps",
                "@rust/api",
                "@rust/proof",
                "@javascript/coverage",
                "@javascript/lint",
                "@javascript/deps",
                "@javascript/api",
                "@javascript/vitest",
                "@javascript/jest",
                "@javascript/playwright",
            ],
            Family::Gsd => &[
                "@gsd/core",
                "@gsd/import",
                "@code/core",
                "@javascript/node-test",
                "@specforge/checks",
                "@rust/cargo",
                "@rust/source",
                "@rust/test",
                "@javascript/source",
                "@rust/coverage",
                "@rust/lint",
                "@rust/deps",
                "@rust/api",
                "@rust/proof",
                "@javascript/coverage",
                "@javascript/lint",
                "@javascript/deps",
                "@javascript/api",
                "@javascript/vitest",
                "@javascript/jest",
                "@javascript/playwright",
            ],
        }
    }

    /// The builtins of the set this host embeds, in [`BUILTINS`] order.
    pub fn builtins(self) -> impl Iterator<Item = &'static Builtin> {
        BUILTINS
            .iter()
            .filter(move |builtin| self.names().contains(&builtin.name))
    }
}

/// Test support: puts the builtins of `family` into a runtime outside the extension load.
#[cfg(feature = "testing")]
pub fn load_family(runtime: &dyn WasmRuntime, family: Family) -> Result<(), LoadError> {
    for builtin in family.builtins() {
        runtime.load(
            builtin.name,
            builtin.bytes,
            Provenance::builtin(builtin.bytes),
        )?;
    }
    Ok(())
}
