//! The candidate vocabulary: what extensions a host could enable declare (ADR 0122). It names, for
//! each kind keyword, every extension that declares it (ADR 0369), and for each field an
//! enhancement adds to another extension's kind, the one extension that declares it. It decides no
//! ownership (ADR 0096): a name it does not know suggests `specforge extensions search`. Beside the
//! checks' suggestions it decides one thing: whether a
//! kind a judged chain or a route part reaches is an unloaded optional peer's ([`UnloadedPeers`],
//! ADR 0331 D7), which makes the part inert instead of a mistake.

use super::populate::keyword;
use serde::{Deserialize, Serialize};
use specforge_protocol_types::ExtensionDeclaration;
use std::collections::{BTreeMap, BTreeSet};

/// The `$comment` of the written form.
const GENERATED: &str = "Generated by `cargo run -p xtask --bin revendor` from the builtins' \
pinned declarations (ADR 0122, ADR 0369). Do not edit.";

/// What extensions a host could enable declare (ADR 0122): each kind keyword with every extension
/// that declares it (ADR 0369), and each field an enhancement adds to another extension's kind with
/// the one extension that declares it. The host hands it to the build
/// ([`super::build_registries_with`]).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CandidateVocabulary {
    /// keyword -> the extensions that declare it, sorted; never empty
    kinds: BTreeMap<String, BTreeSet<String>>,
    /// kind -> field -> extension
    fields: BTreeMap<String, BTreeMap<String, String>>,
}

/// The written form, in its key order: a sorted list of extensions per kind keyword, one extension
/// per enhancement field.
#[derive(Serialize, Deserialize)]
struct Written {
    #[serde(rename = "$comment", default)]
    comment: String,
    #[serde(default)]
    kinds: BTreeMap<String, BTreeSet<String>>,
    #[serde(default)]
    fields: BTreeMap<String, BTreeMap<String, String>>,
}

impl CandidateVocabulary {
    /// The vocabulary `declarations` declare: each kind under its keyword (else its name, as the
    /// registry keys it), with every declaration that declares it (ADR 0369 D1), and each
    /// enhancement field under (target kind, field name), credited to the one declaration that
    /// adds it, by its `name()` (ADR 0096 D2). A kind's own and shared fields are not in it: they
    /// come with their kind. Err names both extensions when two add one enhancement field to one
    /// kind (ADR 0369 D4); a keyword two declare is no error.
    pub fn of(declarations: &[ExtensionDeclaration]) -> Result<Self, String> {
        let mut vocabulary = Self::default();
        for declaration in declarations {
            let extension = declaration.name();
            for kind in &declaration.entities {
                vocabulary
                    .kinds
                    .entry(keyword(kind).to_string())
                    .or_default()
                    .insert(extension.to_string());
            }
            for enhancement in &declaration.enhancements {
                for field in &enhancement.fields {
                    let by_field = vocabulary
                        .fields
                        .entry(enhancement.target_kind.clone())
                        .or_default();
                    if let Some(first) = by_field.insert(field.name.clone(), extension.to_string())
                    {
                        return Err(format!(
                            "{first} and {extension} both add the field '{}' to '{}'",
                            field.name, enhancement.target_kind
                        ));
                    }
                }
            }
        }
        Ok(vocabulary)
    }

    /// The vocabulary a written form says (`to_json`); unreadable text is the empty vocabulary,
    /// so every suggestion falls back to `specforge extensions search` (the spec's fallback). A
    /// text that names one extension per keyword instead of a list is unreadable. Unknown keys
    /// are ignored, and so is a keyword whose list is empty.
    pub fn from_json(text: &str) -> Self {
        match serde_json::from_str::<Written>(text) {
            Ok(mut written) => {
                written.kinds.retain(|_, owners| !owners.is_empty());
                Self {
                    kinds: written.kinds,
                    fields: written.fields,
                }
            }
            Err(_) => Self::default(),
        }
    }

    /// `{"$comment": GENERATED, "kinds": {keyword: [ext, ..]}, "fields": {kind: {field: ext}}}`,
    /// keys and each list sorted, pretty-printed, with a trailing newline.
    pub fn to_json(&self) -> String {
        let written = Written {
            comment: GENERATED.to_string(),
            kinds: self.kinds.clone(),
            fields: self.fields.clone(),
        };
        let mut text =
            serde_json::to_string_pretty(&written).expect("maps of strings always serialize");
        text.push('\n');
        text
    }

    /// The extensions that declare the kind written `keyword`, sorted; empty when none does.
    pub fn kind_owners(&self, keyword: &str) -> Vec<&str> {
        self.kinds
            .get(keyword)
            .into_iter()
            .flatten()
            .map(String::as_str)
            .collect()
    }

    /// Every kind keyword it names, sorted.
    pub fn kind_keywords(&self) -> impl Iterator<Item = &str> {
        self.kinds.keys().map(String::as_str)
    }

    /// The extension that declares the kind written `keyword`, when exactly one does: None when
    /// none declares it and None when several do, so no caller takes the first of several
    /// (ADR 0369 D2). [`Self::kind_owners`] answers for every declarer.
    pub fn kind_owner(&self, keyword: &str) -> Option<&str> {
        match self.kind_owners(keyword).as_slice() {
            [only] => Some(*only),
            _ => None,
        }
    }

    /// The sentence that installs a declarer of the kind written `keyword`, each declarer with its
    /// own command, in the vocabulary's order (ADR 0369 D2); None when nothing declares it.
    pub fn kind_install(&self, keyword: &str) -> Option<String> {
        let commands: Vec<String> = self
            .kind_owners(keyword)
            .into_iter()
            .map(|extension| specforge_common::remedy::command("specforge add {}", &[extension]))
            .collect();
        match commands.as_slice() {
            [] => None,
            [only] => Some(format!("install it with: {only}")),
            several => Some(format!(
                "install one of the extensions that declare it with: {}",
                several.join(" or ")
            )),
        }
    }

    /// What to do about the kind written `keyword` that no loaded extension declares: install an extension that
    /// declares it ([`Self::kind_install`]), else search for one (E024, I210).
    pub fn kind_remedy(&self, keyword: &str) -> String {
        self.kind_install(keyword).unwrap_or_else(|| {
            format!(
                "search for an extension that provides it with: {}",
                specforge_common::remedy::command("specforge extensions search {}", &[keyword])
            )
        })
    }

    /// The extension whose enhancement adds `field` to `kind`.
    pub fn field_owner(&self, kind: &str, field: &str) -> Option<&str> {
        self.fields
            .get(kind)
            .and_then(|fields| fields.get(field))
            .map(String::as_str)
    }

    /// Whether it names nothing.
    pub fn is_empty(&self) -> bool {
        self.kinds.is_empty() && self.fields.is_empty()
    }
}

/// The optional peers of one declaration the project does not load, and the kinds the candidate
/// vocabulary credits to them (ADR 0331 D7): a judged chain or a route part of the declaration that
/// reaches one of those kinds is inert. Any other kind no loaded extension declares is a mistake
/// (W112, E118), a misspelt one or a peer's the vocabulary does not know alike.
pub(crate) struct UnloadedPeers<'a> {
    peers: Vec<&'a str>,
    candidates: &'a CandidateVocabulary,
}

impl<'a> UnloadedPeers<'a> {
    /// The optional peers of `declaration` that `loaded` (the loaded extensions' names) leaves out.
    pub(crate) fn of(
        declaration: &'a ExtensionDeclaration,
        loaded: &[&str],
        candidates: &'a CandidateVocabulary,
    ) -> Self {
        let peers = declaration
            .peers()
            .iter()
            .filter(|p| p.optional && !loaded.contains(&p.name.as_str()))
            .map(|p| p.name.as_str())
            .collect();
        Self { peers, candidates }
    }

    /// Whether `extension` is one of them.
    pub(crate) fn names(&self, extension: &str) -> bool {
        self.peers.contains(&extension)
    }

    /// Whether one of them declares the kind written `keyword`.
    pub(crate) fn declare(&self, keyword: &str) -> bool {
        self.candidates
            .kind_owner(keyword)
            .is_some_and(|owner| self.peers.contains(&owner))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use specforge_extension_sdk::prelude::*;

    fn declare(name: &str, f: impl FnOnce(&mut ContributionsBuilder)) -> ExtensionDeclaration {
        let mut c = ContributionsBuilder::new(ExtensionMeta::new(name, "1.0.0"));
        f(&mut c);
        c.declaration()
    }

    fn gizmo_and_widget() -> Vec<ExtensionDeclaration> {
        let a = declare("@x/a", |c| {
            c.kind("Gizmo", |k| {
                k.keyword("gizmo");
                k.field("size", |f| {
                    f.field_type(FieldType::String);
                });
            });
            c.enhance("widget", |e| {
                e.field("colour", |f| {
                    f.field_type(FieldType::String);
                });
            });
        });
        let b = declare("@x/b", |c| {
            c.kind("Widget", |_| {});
        });
        vec![a, b]
    }

    /// `@x/c`: a second declarer of the keyword `gizmo`.
    fn second_gizmo() -> ExtensionDeclaration {
        declare("@x/c", |c| {
            c.kind("Other", |k| {
                k.keyword("gizmo");
            });
        })
    }

    #[test]
    fn of_maps_each_kind_and_enhancement_field_to_its_declarer() {
        let v = CandidateVocabulary::of(&gizmo_and_widget()).unwrap();
        assert_eq!(v.kind_owners("gizmo"), ["@x/a"]);
        assert_eq!(v.kind_owners("Widget"), ["@x/b"]);
        assert_eq!(v.kind_keywords().collect::<Vec<_>>(), ["Widget", "gizmo"]);
        assert_eq!(v.field_owner("widget", "colour"), Some("@x/a"));
        assert_eq!(v.field_owner("gizmo", "size"), None);
        assert!(v.kind_owners("xyzzy").is_empty());
        assert!(!v.is_empty());
    }

    #[test]
    fn two_candidates_declaring_one_keyword_are_both_listed() {
        let mut declarations = gizmo_and_widget();
        declarations.push(second_gizmo());
        let v = CandidateVocabulary::of(&declarations).unwrap();
        assert_eq!(v.kind_owners("gizmo"), ["@x/a", "@x/c"]);
        // The list is sorted whatever order the declarations come in.
        declarations.reverse();
        let reversed = CandidateVocabulary::of(&declarations).unwrap();
        assert_eq!(reversed.kind_owners("gizmo"), ["@x/a", "@x/c"]);
        assert_eq!(reversed, v);
        assert_eq!(CandidateVocabulary::from_json(&v.to_json()), v);
        // The single-owner answer is for exactly one declarer, never the first of two.
        assert_eq!(v.kind_owner("gizmo"), None);
    }

    #[test]
    fn a_declaration_declaring_one_keyword_twice_is_listed_once() {
        let twice = declare("@x/a", |c| {
            c.kind("Gizmo", |k| {
                k.keyword("gizmo");
            });
            c.kind("Other", |k| {
                k.keyword("gizmo");
            });
        });
        let v = CandidateVocabulary::of(&[twice]).unwrap();
        assert_eq!(v.kind_owners("gizmo"), ["@x/a"]);
    }

    #[test]
    fn the_install_sentence_names_each_declarer_with_its_command() {
        let mut declarations = gizmo_and_widget();
        declarations.push(second_gizmo());
        let v = CandidateVocabulary::of(&declarations).unwrap();
        assert_eq!(
            v.kind_install("Widget").as_deref(),
            Some("install it with: specforge add @x/b")
        );
        assert_eq!(
            v.kind_install("gizmo").as_deref(),
            Some(
                "install one of the extensions that declare it with: specforge add @x/a or specforge add @x/c"
            )
        );
        assert_eq!(v.kind_install("xyzzy"), None);
        assert_eq!(v.kind_remedy("gizmo"), v.kind_install("gizmo").unwrap());
        assert_eq!(
            v.kind_remedy("xyzzy"),
            "search for an extension that provides it with: specforge extensions search xyzzy"
        );
    }

    #[test]
    fn two_candidates_adding_one_field_to_one_kind_are_refused() {
        let mut declarations = gizmo_and_widget();
        declarations.push(declare("@x/c", |c| {
            c.enhance("widget", |e| {
                e.field("colour", |f| {
                    f.field_type(FieldType::String);
                });
            });
        }));
        let err = CandidateVocabulary::of(&declarations).unwrap_err();
        assert!(
            err.contains("@x/a") && err.contains("@x/c") && err.contains("'colour'"),
            "{err}"
        );
    }

    #[test]
    fn the_written_form_reads_back() {
        let mut declarations = gizmo_and_widget();
        declarations.push(second_gizmo());
        let v = CandidateVocabulary::of(&declarations).unwrap();
        let text = v.to_json();
        assert!(text.starts_with("{\n  \"$comment\": "), "{text}");
        assert!(text.ends_with("}\n"), "{text}");
        assert!(
            text.find("\"Widget\"").unwrap() < text.find("\"gizmo\"").unwrap(),
            "sorted: {text}"
        );
        let written: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_eq!(
            written["kinds"],
            serde_json::json!({"Widget": ["@x/b"], "gizmo": ["@x/a", "@x/c"]})
        );
        assert_eq!(
            written["fields"],
            serde_json::json!({"widget": {"colour": "@x/a"}})
        );
        assert_eq!(CandidateVocabulary::from_json(&text), v);
        assert_eq!(
            CandidateVocabulary::from_json(&CandidateVocabulary::default().to_json()),
            CandidateVocabulary::default()
        );
    }

    #[test]
    fn a_malformed_vocabulary_is_empty_so_suggestions_fall_back_to_search() {
        let v = CandidateVocabulary::from_json("{not json");
        assert!(v.kind_owners("feature").is_empty());
        assert!(v.is_empty());
    }

    /// The form before ADR 0369, one extension per keyword, is not read.
    #[test]
    fn a_single_owner_written_form_is_not_read() {
        let v = CandidateVocabulary::from_json(
            r#"{"kinds": {"feature": "@specforge/product"}, "fields": {}}"#,
        );
        assert!(v.kind_owners("feature").is_empty());
        assert!(v.is_empty());
    }

    #[test]
    fn a_keyword_written_with_no_extension_is_not_named() {
        let v = CandidateVocabulary::from_json(r#"{"kinds": {"feature": []}}"#);
        assert_eq!(v.kind_keywords().count(), 0);
        assert_eq!(v.kind_install("feature"), None);
        assert!(v.is_empty());
    }
}
