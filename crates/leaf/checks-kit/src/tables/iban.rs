/// The length of an IBAN of `country`; none for a country with no IBAN.
pub fn length_of(country: &str) -> Option<usize> {
    LENGTHS
        .binary_search_by_key(&country, |(code, _)| code)
        .ok()
        .map(|at| LENGTHS[at].1)
}
